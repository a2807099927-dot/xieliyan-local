// AI 风格提取器 — 提示词存储模块
// 安全设计：所有提示词仅存在于 Rust 二进制中，前端 JS bundle 完全不可见。
// 即使反编译 Rust 二进制，字符串也以编译优化后的形式存在于只读数据段。

/// 获取风格提取指定阶段的提示词。
/// phase: "A" | "B" | "C" | "D"
#[tauri::command]
pub fn ai_get_style_extraction_prompt(phase: String) -> Result<String, String> {
    match phase.as_str() {
        "A" => Ok(PHASE_A_PROMPT.to_string()),
        "B" => Ok(PHASE_B_PROMPT.to_string()),
        "C" => Ok(PHASE_C_PROMPT.to_string()),
        "D" => Ok(PHASE_D_PROMPT.to_string()),
        _ => Err(format!("未知的提取阶段: {}", phase)),
    }
}

/* ── Phase A: 核心技法特征提取（第一步） ── */
const PHASE_A_PROMPT: &str = r#"你是一位专业小说写作技法分析师，任务是对提供的章节文本进行系统性技法提取。
第一步
【你的分析不涉及剧情内容本身，只分析写作技法和结构模式。】
请按以下六个维度逐一分析，每个维度给出：
- 统计数据（频率/比例）
- 典型例句（原文摘录3-5条）
- 规律总结（一句话）
- 用XX或者XXX代替角色名，不允许出现人名
---
## 维度一：对话技法
1. 对话引入方式分布：
- "某某说/道" 前置修饰 → 神态/动作/眼神/无修饰，各占比？
2. 对话收尾处理分布：
- 说完后接 → 心理反应/对方反应/环境切入/直接推进，各占比？
3. 对话与叙述的交替节奏：
- 连续对话最多几轮才插入叙述？
- 叙述插入的平均字数？
---
## 维度二：节奏控制
1. 长短句交替规律：
- 紧张场景的平均句长（字数）
- 舒缓场景的平均句长（字数）
- 单行段出现的典型时机
2. 段落长度分布：
- 对话段平均行数
- 叙述段平均行数
- 描写段平均行数
---
## 维度三：描写技法
1. 外貌描写：
- 首次出场平均字数
- 描写顺序规律（整体→细节？上→下？）
- 正面描写 vs 他人视角比例
2. 气质描写：
- 直接定义 vs 行为暗示比例
- 最常用的暗示手法是什么？
3. 环境描写：
- 出现时机规律（章节开头/情绪转折前/其他）
- 平均字数
- 主要感官通道分布（视觉/听觉/触觉/嗅觉）
4. 氛围描写：
- 标志性词汇/句式（列出Top10）
- 触发场景规律
---
## 维度四：叙事结构
1. 单章结构：
- 开头钩子类型（悬念/动作/对话/环境，各占比）
- 高潮点位置（前1/3 / 中间 / 末尾）
- 结尾类型（悬念收/情绪收/动作收，各占比）
2. 中期弧线（5-15章）：
- 一个事件从引入到爆发平均几章？
- 转折前平均铺垫节点数
3. 情绪曲线：
- 波峰出现频率（平均每几章一次）
- 波峰前的典型铺垫手法
---
## 维度五：视角与心理描写
1. 视角稳定性：
- 章节内是否切换视角？切换信号词是什么？
2. 心理描写深度分布：
- 浅层（动作反应）/ 中层（直接想法）/ 深层（潜意识/隐喻）各占比？
3. 心理描写触发时机：
- 什么场景下最密集？
---
## 维度六：信息密度
1. 每章平均引入新信息点数量
2. 新信息投放节奏（开头集中/均匀分布/结尾集中）
3. 是否有伏笔结构？平均埋设到回收间隔章数？
---
## 输出格式要求
每个维度结束后输出一个JSON块：
{
  "dimension": "维度名",
  "stats": { ... },
  "examples": [ ... ],
  "rule_summary": "..."
}
全部分析完后，额外输出一个总结块：
{
  "genre": "题材",
  "craft_fingerprint": {
    "dialogue_style": "...",
    "rhythm_style": "...",
    "description_style": "...",
    "structure_style": "..."
  },
  "top_patterns": [ ... ]
}"#;

/* ── Phase B: 触发条件与对比案例（第二步） ── */
