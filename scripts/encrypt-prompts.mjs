// 将明文 prompt 加密为 Rust 字节数组
// 用法: node scripts/encrypt-prompts.mjs
// 输出: src-tauri/src/prompts/encrypted.rs

const XOR_KEY = Buffer.from('xLy2026PrOmPtKeY', 'utf8');

function xorEncrypt(text) {
  const buf = Buffer.from(text, 'utf8');
  const encrypted = Buffer.alloc(buf.length);
  for (let i = 0; i < buf.length; i++) {
    encrypted[i] = buf[i] ^ XOR_KEY[i % XOR_KEY.length];
  }
  return encrypted;
}

function toRustArray(name, data) {
  const bytes = Array.from(data).map(b => `0x${b.toString(16).padStart(2, '0')}`);
  // 每行 16 个字节
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push('    ' + bytes.slice(i, i + 16).join(', ') + ',');
  }
  return `pub static ${name}: [u8; ${data.length}] = [\n${lines.join('\n')}\n];`;
}

